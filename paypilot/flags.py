"""Typed decision flags and the non-overridable safety boundary (C0)."""
from __future__ import annotations

from enum import StrEnum


class Flag(StrEnum):
    """Flags emitted by checks, resolution, and reconciliation."""

    # Input
    MISSING_FIELD = "MISSING_FIELD"
    PARSE_FAILED = "PARSE_FAILED"
    UNSUPPORTED_REQUEST = "UNSUPPORTED_REQUEST"
    OUT_OF_PERIOD = "OUT_OF_PERIOD"
    CREDIT_LINE = "CREDIT_LINE"
    UNSUPPORTED_CURRENCY = "UNSUPPORTED_CURRENCY"
    NON_POSITIVE_AMOUNT = "NON_POSITIVE_AMOUNT"

    # Identity
    PAYEE_UNRESOLVED = "PAYEE_UNRESOLVED"
    PAYEE_TIE = "PAYEE_TIE"
    LOOKALIKE = "LOOKALIKE"
    FUZZY_MATCH = "FUZZY_MATCH"
    PARENT_BRAND = "PARENT_BRAND"
    WEBSITE_IDENTITY_CLAIM_ONLY = "WEBSITE_IDENTITY_CLAIM_ONLY"
    VENDOR_ONBOARDING_REQUIRED = "VENDOR_ONBOARDING_REQUIRED"
    VENDOR_MASTER_CONFLICT = "VENDOR_MASTER_CONFLICT"

    # Duplicates
    DUPLICATE_INVOICE = "DUPLICATE_INVOICE"
    DUPLICATE_TRANSACTION = "DUPLICATE_TRANSACTION"
    ALREADY_PAID = "ALREADY_PAID"
    DUPLICATE_PAYMENT = "DUPLICATE_PAYMENT"
    DUPLICATE_DEBIT = "DUPLICATE_DEBIT"

    # Purchase orders and account mapping
    PO_MISSING = "PO_MISSING"
    PO_NOT_FOUND = "PO_NOT_FOUND"
    PO_VENDOR_MISMATCH = "PO_VENDOR_MISMATCH"
    PO_AMOUNT_MISMATCH = "PO_AMOUNT_MISMATCH"
    PO_QTY_MISMATCH = "PO_QTY_MISMATCH"
    PO_EXHAUSTED = "PO_EXHAUSTED"
    ACCOUNT_UNMAPPED = "ACCOUNT_UNMAPPED"

    # Bank details
    BANK_CHANGED = "BANK_CHANGED"
    BANK_CHANGE_REQUEST = "BANK_CHANGE_REQUEST"
    IFSC_INVALID = "IFSC_INVALID"

    # Sources and limits
    SOURCE_UNAVAILABLE = "SOURCE_UNAVAILABLE"
    CREDITS_EXHAUSTED = "CREDITS_EXHAUSTED"
    COST_LIMIT = "COST_LIMIT"
    TIME_LIMIT = "TIME_LIMIT"

    # Payments and reconciliation
    PROVIDER_TIMEOUT = "PROVIDER_TIMEOUT"
    PAYMENT_UNCERTAIN = "PAYMENT_UNCERTAIN"
    WRONG_PAYEE_SUSPECTED = "WRONG_PAYEE_SUSPECTED"
    AMOUNT_MISMATCH = "AMOUNT_MISMATCH"
    SETTLEMENT_MISMATCH = "SETTLEMENT_MISMATCH"
    RETURNED_PAYMENT = "RETURNED_PAYMENT"
    REVERSED_PAYMENT = "REVERSED_PAYMENT"
    STALE_APPROVAL = "STALE_APPROVAL"
    VENDOR_CONTAINED = "VENDOR_CONTAINED"

    # System failures are fail-closed and never enter decision rules.
    PERSISTENCE_FAILURE = "PERSISTENCE_FAILURE"


NEVER_OVERRIDABLE: frozenset[Flag] = frozenset(
    {
        Flag.PAYEE_UNRESOLVED,
        Flag.PAYEE_TIE,
        Flag.LOOKALIKE,
        Flag.PARENT_BRAND,
        Flag.VENDOR_MASTER_CONFLICT,
        Flag.BANK_CHANGED,
        Flag.BANK_CHANGE_REQUEST,
        Flag.IFSC_INVALID,
        Flag.DUPLICATE_INVOICE,
        Flag.ALREADY_PAID,
        Flag.DUPLICATE_PAYMENT,
        Flag.DUPLICATE_DEBIT,
        Flag.WRONG_PAYEE_SUSPECTED,
        Flag.AMOUNT_MISMATCH,
        Flag.PAYMENT_UNCERTAIN,
        Flag.PROVIDER_TIMEOUT,
        Flag.RETURNED_PAYMENT,
        Flag.REVERSED_PAYMENT,
        Flag.MISSING_FIELD,
        Flag.PARSE_FAILED,
        Flag.UNSUPPORTED_REQUEST,
        Flag.VENDOR_CONTAINED,
        Flag.PERSISTENCE_FAILURE,
    }
)
